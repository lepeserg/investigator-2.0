# Ловим только «зарегистрирован … В <чужом органе>» — направление важно:
#  · окно [^.]{0,40} не пересекает границу предложения и дату «12.05.2026» → своя
#    «зарегистрирован 12.05.2026 в КРСП {ОРГАН}» под флаг НЕ попадает;
