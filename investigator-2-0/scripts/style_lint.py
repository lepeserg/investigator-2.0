_INI_TOP_MIN = 5        # «основной» вариант должен быть явно основным…
_INI_RARE_MAX = 1       # …а подозрительный — встретиться ровно раз


def _surname_stem(s):
    'Грубая основа фамилии: снять падежное окончание. «Фамилия» → «Фамилия».'
    for suf in _SURNAME_SUF:
        if s.lower().endswith(suf) and len(s) - len(suf) >= 4:
            return s[:len(s) - len(suf)]
    return s


