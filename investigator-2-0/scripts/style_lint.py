def _mkdate(d, m, y):
    import datetime
    try:
        return datetime.date(int(y), int(m), int(d))
    except Exception:
        return None


def _doc_date(paras):
    """Дата документа из ШАПКИ: строка «место — дата». None — шапки нет, проверка пропускается.

    ⛔ Максимум по первым абзацам брать нельзя: в шапке рядом стоит дата ВУД либо дата приказа,
    и документ получил бы чужую дату. Берём ровно строку «населённый пункт — дата»."""
    for t in [p.strip() for p in paras if p and p.strip()][:_HEAD_SCAN_PARAS]:
        flat = re.sub(r"[\s\u00a0]+", " ", t).strip()
        if not (_place_date_line(t) or _HEAD_CITY.match(flat)):
            continue
        m = _DATE_WORD.search(flat)
        if m:
            got = _mkdate(m.group(1), _MONTHS_RU[m.group(2).lower()], m.group(3))
            if got:
                return got
        m = _DATE_NUM.search(flat)
        if m:
            got = _mkdate(*m.groups())
            if got:
                return got
    return None


