_HF_PART_RX = re.compile(r"^word/(?:header|footer)\d*\.xml$")
_PARA_RX = re.compile(r"<w:p[ >].*?</w:p>|<w:p/>", re.S)
_PPR_RX = re.compile(r"<w:pPr>.*?</w:pPr>", re.S)
# keepNext без явного w:val="0"/"false" (Word пишет отключение именно так)
_KEEPNEXT_RX = re.compile(r"<w:keepNext(?![^>]*w:val=\"(?:0|false)\")")


def _xml_text(xml):
    """Текст из куска WordprocessingML — общие правила word_text.xml_text: коды полей (PAGE,
    MERGEFORMAT) и удалённое при рецензировании выброшены, w:tab → \\t."""
    return xml_text(xml)


# Модель «знаки → строки → страницы». Разбиение на страницы делает Word при вёрстке, поэтому это
# ОЦЕНКА, а не факт (§16.17). Константы подобраны по эталону `docProps/<Pages>`: TNR 13 pt даёт
# ≈125 твипов на знак, строка ≈280 твипов. Замер на корпусе (236 файлов с записанным <Pages>,
# из них 71 без таблиц — таблицы модель не описывает): страница угадана ТОЧНО у 70 %, в пределах
# ±1 страницы — у 99 %. Поэтому оценка годится как СИГНАЛ и не годится как доказательство.
_TWIPS_PER_CHAR = 125
_TWIPS_PER_LINE = 280


def _page_geometry(xml):
    """(знаков в строке, строк на листе) по sectPr документа и его основному межстрочному."""
    m = re.search(r'<w:pgSz[^>]*w:w="(\d+)"[^>]*w:h="(\d+)"', xml)
    pw, ph = (int(m.group(1)), int(m.group(2))) if m else (11906, 16838)   # A4 по умолчанию
    mar = {"top": 1134, "right": 850, "bottom": 1134, "left": 1701}
    m = re.search(r"<w:pgMar[^>]*/>", xml)
    if m:
        for k in mar:
            mm = re.search(r'w:%s="(-?\d+)"' % k, m.group(0))
            if mm:
                mar[k] = abs(int(mm.group(1)))
    line_h = _TWIPS_PER_LINE
    vals = re.findall(r'<w:spacing[^>]*w:line="(\d+)"[^>]*w:lineRule="(exact|atLeast)"', xml)
    if vals:
        cnt = {}
        for v, _rule in vals:
            cnt[int(v)] = cnt.get(int(v), 0) + 1
        line_h = max(200, min(500, max(cnt, key=cnt.get)))
    cpl = max(20, (pw - mar["left"] - mar["right"]) // _TWIPS_PER_CHAR)
    lpp = max(10, (ph - mar["top"] - mar["bottom"]) // line_h)
    return cpl, lpp


def _docx_raw(path):
    """{'hf': текст колонтитулов, 'paras': [(текст, keep_with_next)], 'cpl':, 'lpp':}.
    None — файл прочитать не удалось (тогда все зип-проверки молча пропускаются: так линтер
    остаётся работоспособным на текстовых заглушках и на битых архивах)."""
    try:
        with zipfile.ZipFile(path) as z:
            names = z.namelist()
            hf = "\n".join(_xml_text(z.read(n).decode("utf-8", "replace"))
                           for n in names if _HF_PART_RX.match(n))
            xml = z.read("word/document.xml").decode("utf-8", "replace")
    except Exception:
        return None
    body = xml.split("<w:body>", 1)[-1]
    paras = []
    for m in _PARA_RX.finditer(body):
        p = m.group(0)
        ppr = _PPR_RX.search(p)
        paras.append((_xml_text(p), bool(ppr and _KEEPNEXT_RX.search(ppr.group(0)))))
    cpl, lpp = _page_geometry(xml)
    return {"hf": hf, "paras": paras, "cpl": cpl, "lpp": lpp}


