def _looks_like_statcard(paras):
    """Документ — БЛАНК статкарты ГВП (Ф-1 · Ф-1.1 · Ф-1.2 · Ф-2 · Ф-5) либо комплект с нею."""
    lines = [(t or "").strip() for t in paras]
    forms = sum(1 for t in lines if _STATCARD_FORM.match(t))
    return forms >= 2 or (forms >= 1 and any(_STATCARD_MARK.search(t) for t in lines))


