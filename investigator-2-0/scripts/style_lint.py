# ⛔ ЗЕРКАЛО: поиск подписного блока ПРОДУБЛИРОВАН в `docx_edit.py` (операция `glue_signature`,
#   которая этот же флаг и чинит). Тождество обязано держаться:
#       style_lint._SIG_LINE       ↔ docx_edit._SIG_FIO_RX        (регулярка — БУКВА В БУКВУ)
#       style_lint._SIG_BLOCK_MAX  ↔ docx_edit._SIG_BLOCK_MAX     (= 6)
#       style_lint._sig_block      ↔ docx_edit._signature_block   (тот же ход вверх и те же отсечки:
#                                    длина > 120 или конец на «.:;» — стоп; ≤ 2 пустых отбивки внутри)
#   Единственное РАЗРЕШЁННОЕ расхождение: docx_edit добавляет к блоку до `_SIG_LEAD_BLANKS` = 2
#   ВЕДУЩИХ пустых абзацев (в `make_docx` отбивки — часть блока и тоже несут keepNext), а линтер
#   их отбрасывает: флаг смотрит на скрепление содержательных абзацев.
#   ⚠ Разойдутся — склейка ляжет НЕ НА ТЕ абзацы, а флаг `подпись-разорвана` останется гореть
#   после починки. Меняешь здесь — сверь там (и наоборот).
_SIG_BLOCK_MAX = 6          # длиннее блок не бывает: орган (2–3 строки) + звание + пустые отбивки
_SIG_BLOCK_MIN = 3          # блок из 1–2 абзацев рвать почти нечему
_SIG_PAGE_TAIL = 0.80       # «низ листа» — последняя пятая часть


def _sig_block(paras, i):
    """Индексы абзацев подписного блока, кончающегося строкой с Ф.И.О. (индекс i).
    Пустые абзацы-отбивки внутри блока (их в бланках 1–2) в блок ВХОДЯТ: они тоже должны нести
    keepNext, иначе разрыв ляжет ровно на них."""
    blk, j, empty = [i], i - 1, 0
    while j >= 0 and len(blk) < _SIG_BLOCK_MAX:
        t = paras[j][0].strip()
        if not t:
            empty += 1
            if empty > 2:
                break
            blk.insert(0, j)
            j -= 1
            continue
        if len(t) > 120 or t[-1] in ".:;":
            break               # это уже текст документа, а не шапка подписи
        blk.insert(0, j)
        j -= 1
    while blk and not paras[blk[0]][0].strip():
        blk.pop(0)
    return blk


