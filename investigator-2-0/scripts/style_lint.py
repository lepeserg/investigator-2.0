# полужирны ПО ЭТАЛОНУ — глушить их нельзя (замер: без сужения 4 % файлов, почти все ложные).
_EVIDENCE_LEAD = re.compile(
    r"^\s*(?:[-–—]\s*)?(?:Показани|Протокол|Заключени|Справк|Сообщени|Выписк|Рапорт|Акт\b)"
    r"|из котор(?:ых|ого)\s+следует", re.IGNORECASE)


def _check_header_donor(raw, path):
    """`след-донора-колонтитул`: номер дела/КРСП в колонтитуле не подтверждён ни телом документа,
    ни именем файла, ни путём папки дела (правило 13, §2.22)."""
    out = []
    hf = raw["hf"]
    if not hf.strip():
        return out
    body = _nospace("\n".join(t for t, _k in raw["paras"]))
    where = _nospace(path or "")
    body_nums = {m.group(0) for m in _CASE_NO_RX.finditer(body)}
    seen = set()
    cand = [(m.group(0), m.group(1)) for m in _CASE_NO_RX.finditer(_nospace(hf))]
    cand += [("КРСП № " + m.group(1), m.group(1)) for m in _KRSP_NO_RX.finditer(_nospace(hf))]
    for shown, tail in cand:
        if shown in seen:
            continue
        seen.add(shown)
        in_body = _nospace(shown) in body or re.search(r"(?<!\d)%s(?!\d)" % tail, body)
        in_path = re.search(r"(?<!\d)%s(?!\d)" % tail, where)
        if in_body or in_path:
            continue
        if body_nums:
            msg = ("в КОЛОНТИТУЛЕ стоит № «%s», а в теле документа — № %s. Это след донора: "
                   "колонтитул при клонировании не правится вместе с телом (правило 13, §2.22). "
                   "Сверить с делом и заменить" % (shown, ", ".join(sorted(body_nums))))
        else:
            msg = ("номер «%s» в КОЛОНТИТУЛЕ не подтверждён НИЧЕМ: его нет ни в теле документа, "
                   "ни в имени файла, ни в пути папки дела. В ВУД номер живёт только в "
                   "колонтитуле (§2.22), поэтому донорский номер здесь ничем не ловится глазами — "
                   "сверить с делом (правило 13)" % shown)
        out.append((0, "след-донора-колонтитул", msg, hf.strip().replace("\n", " · ")[:110]))
    return out


def _check_initials(paras):
    """`фамилия-без-инициалов`: одна фамилия несёт разные инициалы (правило 33)."""
    counts, on_sig = {}, {}
    for text in paras:
        if not text or not text.strip():
            continue
        sig = bool(_SIG_LINE.search(text))
        pairs = [(m.group(3), m.group(1) + m.group(2)) for m in _FIO_INI_FIRST.finditer(text)]
        pairs += [(m.group(1), m.group(2) + m.group(3)) for m in _FIO_INI_LAST.finditer(text)]
        for surname, ini in pairs:
            if not _SURNAME_LIKE.search(surname):
                continue            # обычное слово перед инициалами, а не фамилия
            key = _surname_stem(surname)
            counts.setdefault(key, {})[ini] = counts.setdefault(key, {}).get(ini, 0) + 1
            if sig:
                on_sig.setdefault((key, ini), True)
    out = []
    for key, c in sorted(counts.items()):
        if len(c) < 2:
            continue
        ranked = sorted(c.items(), key=lambda kv: -kv[1])
        top, top_n = ranked[0]
        rare, rare_n = ranked[-1]
        if rare_n > _INI_RARE_MAX:
            continue                # оба варианта встречаются часто — это однофамильцы
        if top_n < _INI_TOP_MIN and not on_sig.get((key, rare)):
            continue
        detail = ", ".join("%s %s (%d)" % (i, key, n) for i, n in ranked)
        out.append((0, "фамилия-без-инициалов",
                    "фамилия «%s» встречается с РАЗНЫМИ инициалами: %s. Вариант «%s» — единственный: "
                    "похоже, фамилию заменили, а инициалы остались от донора%s. Сверить по "
                    "первоисточнику (ордер, постановление, паспорт) во ВСЕХ местах, включая подпись "
                    "и колонтитул (правило 33). Однофамильцы — флаг ложный"
                    % (key, detail, rare,
                       " (он стоит в ПОДПИСНОЙ строке)" if on_sig.get((key, rare)) else ""),
                    ""))
    return out


def _check_signature_break(raw):
    """`подпись-разорвана`: подписной блок не скреплён `keepNext` и, по оценке вёрстки, стоит на
    границе листа. ⛔ Проверяется НЕ факт разрыва (его знает только Word), а отсутствие скрепления
    плюс приблизительная позиция блока — см. комментарий у `_SIG_BLOCK_MIN`."""
    paras, cpl, lpp = raw["paras"], raw["cpl"], raw["lpp"]
    if not paras:
        return []
    lines, pref = [], [0]
    for t, _k in paras:
        s = t.strip()
        lines.append(max(1, -(-len(s) // cpl)) if s else 1)
        pref.append(pref[-1] + lines[-1])
    if pref[-1] <= lpp:
        return []                   # одностраничный документ — рвать нечего
    out = []
    for i, (t, _k) in enumerate(paras):
        if not _SIG_LINE.search(t):
            continue
        blk = _sig_block(paras, i)
        if len(blk) < _SIG_BLOCK_MIN:
            continue
        if all(paras[x][1] for x in blk[:-1]):
            continue                # блок скреплён — Word его не разорвёт
        start, end = pref[blk[0]], pref[blk[-1] + 1]
        pos = start % lpp
        straddle = (start // lpp) != ((end - 1) // lpp)
        if not (straddle or pos >= lpp * _SIG_PAGE_TAIL):
            continue
        # ⚠ Номер абзаца НЕ выводим: здесь нумерация сырого document.xml (вместе с абзацами
        # таблиц), она не совпадает с нумерацией остальных флагов. Место указывает первая
        # строка блока в снипете.
        out.append((0, "подпись-разорвана",
                    "подписной блок (%d абз.) НЕ скреплён: у абзацев блока нет `keep_with_next` "
                    "(`w:keepNext`), а по оценке вёрстки блок начинается в нижней части листа "
                    "(строка %d из %d на странице)%s. Word ничем не удержан от разрыва — на "
                    'следующую страницу уедет хвост (реальный провал: ВУД 001849, на третьей '
                    "странице осталась одна строка звания). Выставить keepNext на всех абзацах "
                    "блока, кроме последнего, и на последнем абзаце текста перед ним (§16.17). "
                    "⛔ Позиция листа здесь ОЦЕНКА (модель строк/страниц, точна у 70 %% файлов "
                    "корпуса, ±1 страница у 99 %%): факт разрыва показывает только рендер в PDF. "
                    "⛔ Не «чинить» ручным разрывом страницы перед подписью"
                    % (len(blk), pos + 1, lpp, ", блок пересекает границу листа" if straddle else ""),
                    paras[blk[0]][0].strip()[:70]))
    return out


# Старая редакция углового штампа (надпись бланка 384 ВСО). Эталон с 09.09.2026 — бумажный бланк
# (02a-format-profile «Модель бланка» п. 2); доноры до этой даты несут «ВСУ СК России по ЦВО»,
# «(по гарнизону)», «г. Казань, Россия, 420111». Лечение — {"op": "stamp"} в docx_edit.
_OLD_STAMP = re.compile(r"ВСУ СК России по ЦВО|\(по гарнизону\)|г\. Казань, Россия, 420111")


_STYLE_QUOTES = re.compile(r'«[^»]*»|„[^“]*“|“[^”]*”|"[^"\n]*"')
_STYLE_AND_OR = re.compile(r"\bи\s*/\s*или\b", re.IGNORECASE)
_STYLE_UNTIL = re.compile(r"\bдо\s+(\d{1,2})\.(\d{1,2})\.(\d{4})\b", re.IGNORECASE)
_STYLE_EXPLICIT_END = re.compile(
    r"^\s*,?\s*(?:года\s*|г\.\s*)?(?:включительно\b|не\s+включая\b)", re.IGNORECASE)
_STYLE_LAST_PERSON = re.compile(
    r"\bпоследн(?:ий|его|ему|им|ем|яя|ей|юю)\b"
    r"(?!\s+(?:раз|день|дня|дню|днем|месяц|год|лет|лист|страниц|срок|момент|номер|абзац|вопрос|пункт)[а-яё]*\b)",
    re.IGNORECASE)


def _legal_style_findings(text):
    """Вернуть кандидаты на сверку формы без выбора смысла и без изменения текста."""
    # Пробелы сохраняют смещения. Содержание цитаты может быть значимым доказательством,
    # поэтому не предлагаем уточнять его от имени составителя. Непарные кавычки не маскируем.
    plain = _STYLE_QUOTES.sub(lambda m: " " * len(m.group()), text)
    out = []

    def add(label, message, match):
        start = max(0, match.start() - 35)
        end = min(len(text), match.end() + 55)
        snippet = ("…" if start else "") + text[start:end].strip() + ("…" if end < len(text) else "")
        out.append((label, message, snippet))

    m = _STYLE_AND_OR.search(plain)
    if m:
        add("стиль-проверить-перечень",
            "«и/или»: проверить, нужны все элементы или допустим выбор. "
            "Однозначную конструкцию сохранить; союз не заменять без основания.", m)
    for m in _STYLE_UNTIL.finditer(plain):
        if _mkdate(*m.groups()) is None or _STYLE_EXPLICIT_END.match(plain[m.end():]):
            continue
        add("стиль-проверить-границу",
            "«до [дата]»: проверить включённость границы срока или периода по источнику. "
            "В показаниях сохранить сообщённую точность; «включительно» не добавлять автоматически.", m)
        break
    people = {(_surname_stem(m.group(1)).casefold(), m.group(2), m.group(3))
              for m in _FIO_INI_LAST.finditer(plain)}
    m = _STYLE_LAST_PERSON.search(plain)
    if len(people) >= 2 and m:
        add("стиль-проверить-отсылку",
            "«последний» при нескольких Ф.И.О.: проверить исполнителя по контексту и источнику. "
            "При однозначной отсылке правка не требуется; неизвестное лицо не выбирать по догадке.", m)
    return out


def lint(path, genre=None, allow_foreign_reg=False, status_verified=None, legal_style=False):
    is_statcard = genre in _STATCARD_GENRES
    is_postanovlenie = genre in _POSTANOVLENIE_GENRES
    n_table = None          # с какого индекса пошли ЯЧЕЙКИ (для статкарты); None — не определено
    paras = generic = None
    global _LAST_AUTO_STATCARD
    _LAST_AUTO_STATCARD = False
    if not genre:
        generic = _extract_paragraphs(path)
        if _looks_like_statcard(generic):
            is_statcard = _LAST_AUTO_STATCARD = True    # бланк опознан сам, жанр вспоминать не надо
    if is_statcard:
        got = _extract_statcard(path)
        if got is not None:
            paras, n_table = got
    if paras is None:
        paras = generic if generic is not None else _extract_paragraphs(path)
    n_body = _body_paragraph_count(path) if genre == "oz" else None
    # Подписной блок целиком (а не только строка Ф.И.О.): в постановлении его абзацы —
    # «Следователь 384 военного следственного отдела<TAB>капитан юстиции» — тоже свёрстаны
    # табуляциями и пробелами. Границы блока берём ОБЩИМ хелпером `_sig_block` (см. зеркало
    # в docx_edit), чтобы гасить ровно то, что склеивает `glue_signature`.
    sig_idx = set()
    if is_postanovlenie:
        _pairs = [(t or "", False) for t in paras]
        for _i, _t in enumerate(_pairs):
            if _SIG_LINE.search(_t[0]):
                sig_idx.update(_sig_block(_pairs, _i))
    findings = []
    checks = list(CHECKS)
    if allow_foreign_reg or (genre in _FOREIGN_REG_ALLOWED_GENRES):
        # материал у нас не регистрировался и уходит обратно — чужой номер законен и обязателен
        checks = [c for c in checks if c[0] != "чужая-регистрация"]
    if genre and genre in GENRE_CHECKS:
        checks += GENRE_CHECKS[genre]

    for i, text in enumerate(paras):
        if not text or not text.strip():
            continue
        is_sig = bool(_SIG_LINE.search(text))
        # Вёрстка бланка: место-дата, легенды и линейки — ВСЕГДА; подписной блок целиком —
        # только по --genre postanovlenie (без жанра гасится лишь сама строка Ф.И.О.).
        blank_layout = _place_date_line(text) or _blank_layout_line(text) or (
            is_postanovlenie and i in sig_idx)
        in_table = is_statcard and n_table is not None and i >= n_table
        if legal_style and not is_statcard and not blank_layout and not is_sig:
            findings.extend((i + 1, label, msg, snippet)
                            for label, msg, snippet in _legal_style_findings(text))
        for label, rx, msg in checks:
            if (is_sig or blank_layout) and label in _SPACING_CHECKS:
                continue  # выравнивание подписи / вёрстка бланка — не «двойной пробел»
            if in_table and label in _TYPO_CHECKS:
                continue  # печатная легенда графы: типографике не подлежит (§ бланк ГВП)
            if label in _LIST_EXEMPT and _LIST_LINE.match(text):
                continue  # абзац-перечень: «;» между пунктами законна
            m = _first_inner(rx, text) if label in _SPACING_CHECKS else rx.search(text)
            if m:
                snippet = text.strip()
                if len(snippet) > 90:
                    s = max(0, m.start() - 30)
                    snippet = ("…" if s > 0 else "") + text[s:m.start() + 60].strip() + "…"
                findings.append((i + 1, label, msg, snippet))

        # ОЗ: абзац-показания — раскрыт ли по существу (правило 26, §07.05.8).
        # Только ТЕЛО документа: в ячейках таблиц «Показания … л.д. …» — это ссылки, не изложение.
        if (genre == "oz" and _OZ_TESTIMONY.match(text)
                and (n_body is None or i < n_body)):
            body = text.strip()
            if len(body) < _OZ_MIN_CHARS:
                findings.append((i + 1, "показания-не-раскрыты",
                                 f"абзац показаний короче {_OZ_MIN_CHARS} знаков ({len(body)}) — похоже на ярлык, "
                                 "а не на содержание. Раскрыть по протоколу допроса (первоисточник, §07.05.8 п. 3); "
                                 "источника нет — задать вопрос пользователю, а не сокращать",
                                 body[:110] + ("…" if len(body) > 110 else "")))
            if not _DATE_ANY.search(body):
                findings.append((i + 1, "показания-без-дат",
                                 "в показаниях нет ни одной даты — даты (и время, где есть) в показаниях "
                                 "обязательны, это предмет доказывания ст. 73 УПК (§07.05.4)",
                                 body[:110] + ("…" if len(body) > 110 else "")))

    # ⛔ Старая редакция углового штампа. Надписи (`w:txbxContent`) в `_extract_paragraphs` не
    # входят (там тело, таблицы, колонтитулы), поэтому проверка читает document.xml сама и даёт ОДИН
    # флаг на документ. На корпусе 09.09.2026 срабатывает на КАЖДОМ документе от старого донора —
    # это не ложный флаг, а состояние доноров: новый документ обязан уйти с эталонным угловиком.
    try:
        with zipfile.ZipFile(path) as _z:
            _xml = _z.read("word/document.xml").decode("utf-8", "replace")
        _boxes = re.findall(r"<w:txbxContent>.*?</w:txbxContent>", _xml, re.S)
        _m = _OLD_STAMP.search(" ".join(re.sub(r"<[^>]+>", " ", b) for b in _boxes))
        if _m:
            findings.append((0, "угловик-старый",
                             "угловой штамп донора — старая редакция; эталон — бумажный бланк 384 ВСО "
                             "(02a «Модель бланка» п. 2): привести операцией {\"op\": \"stamp\"} (docx_edit)",
                             _m.group(0)))
    except Exception as e:
        print(f"⚠ проверка углового штампа не выполнена: {e}", file=sys.stderr)

    # ⛔ СТРУКТУРНЫЕ следы ИИ/рабочего процесса (правило 38): примечания, непринятые правки,
    # скрытый текст, маркеры инструмента в свойствах. Замер на 400 файлах корпуса:
    # 1 срабатывание (comments.xml в ИИ-сводке) — и то настоящая находка, ложных нет.
    try:
        with zipfile.ZipFile(path) as _z:
            _names = _z.namelist()
            _body = _z.read("word/document.xml").decode("utf-8", "replace")
            _core = (_z.read("docProps/core.xml").decode("utf-8", "replace")
                     if "docProps/core.xml" in _names else "")
            _app = (_z.read("docProps/app.xml").decode("utf-8", "replace")
                    if "docProps/app.xml" in _names else "")
        if "word/comments.xml" in _names:
            findings.append((0, "след-ИИ-структура",
                             "в файле есть ПРИМЕЧАНИЯ (comments.xml) — в готовом процессуальном "
                             "документе их быть не должно, удалить в Word (Рецензирование)", ""))
        if "<w:ins " in _body or "<w:del " in _body:
            findings.append((0, "след-ИИ-структура",
                             "непринятые ИСПРАВЛЕНИЯ (track changes, w:ins/w:del) — принять/отклонить "
                             "все правки перед выдачей", ""))
        if "<w:vanish/>" in _body or "<w:vanish " in _body:
            findings.append((0, "след-ИИ-структура",
                             "СКРЫТЫЙ текст (w:vanish) — в готовом документе скрытого текста "
                             "быть не должно", ""))
        if "python-docx" in _core or "LibreOffice" in _app:
            findings.append((0, "след-ИИ-структура",
                             "свойства файла несут маркер инструмента (python-docx / LibreOffice-"
                             "песочница) — прогнать scripts/doc_meta.py clean", ""))
    except Exception as e:
        print(f"⚠ проверка структурных следов ИИ (примечания, правки, скрытый текст) "
              f"не выполнена: {e}", file=sys.stderr)

    # Локальный пример исключён из публичной поставки.
    # наследовала жирный лид «Показания свидетеля …» на весь абзац. Заголовки (КАПС) и
    # короткие грифы не трогаем.
    for idx, text, share in _bold_share_paragraphs(path):
        body = text.strip()
        if (share > 0.95 and len(body) >= _ALLBOLD_MIN_CHARS and body != body.upper()
                and not body.endswith(":") and _EVIDENCE_LEAD.search(body)):
            findings.append((idx + 1, "абзац-целиком-жирный",
                             f"абзац из {len(body)} знаков полностью полужирный — обычно след правки "
                             "через первый run (наследует жирный ввод доказательства). Полужирным "
                             "оставить только ввод («Показания свидетеля Ф.И.О.»), тело — обычным "
                             "(docx_edit: replace_paragraph(..., lead=«…»))",
                             body[:110] + ("…" if len(body) > 110 else "")))

    # Допрос подозреваемого/обвиняемого — наличие обязательных блоков (§06.01.13)
    if genre in ("dopros_pod", "допрос_подозреваемого"):
        whole_doc = "\n".join(paras)
        is_first = not _NOT_FIRST_DOPROS.search(whole_doc)
        if len(whole_doc) >= _DOPROS_MIN_CHARS:
            for label, rx, msg in _DOPROS_BLOCKS:
                if label in _FIRST_DOPROS_ONLY and not is_first:
                    continue  # дополнительный/повторный: биографию и здоровье не переписывают
                if not re.search(rx, whole_doc, re.IGNORECASE):
                    findings.append((0, label, msg, ""))

            # Блок ЛИЧНОСТИ — по числу раскрытых групп (только первый допрос)
            if is_first:
                have = [g for g, rx in _LICHNOST_GROUPS.items() if rx.search(whole_doc)]
                if len(have) < _LICHNOST_MIN_GROUPS:
                    missing = [g for g in _LICHNOST_GROUPS if g not in have]
                    findings.append((0, "нет-блока-личность",
                                     "блок ЛИЧНОСТИ (жизненный путь) не раскрыт — найдено групп: "
                                     f"{len(have)} из {len(_LICHNOST_GROUPS)} "
                                     f"(есть: {', '.join(have) or '—'}; нет: {', '.join(missing)}). "
                                     "Анкета 14 пунктов блок НЕ заменяет — §06.01.13 блок 2, "
                                     "14 позиций, место — сразу после блока прав", ""))

            # Локальный пример исключён из публичной поставки.
            if is_first:
                pos = {}
                for name, rx in _ORDER_MARKERS:
                    for i, text in enumerate(paras):
                        if text and rx.search(text):
                            pos[name] = i
                            break
                order = [n for n, _ in _ORDER_MARKERS if n in pos]
                if len(order) == 3:
                    got = sorted(order, key=lambda n: pos[n])
                    if got != [n for n, _ in _ORDER_MARKERS]:
                        findings.append((0, "порядок-блоков",
                                         'нарушен порядок блоков: должно быть «права → Фамилия '
                                         "данные → психофизическое состояние → эпизоды» (§06.01.13 блок 3), "
                                         "фактически: " + " → ".join(got), ""))

    # ⛔ Нормативная ссылка словом вместо сокращения (§2.11 формата).
    for i, text in enumerate(paras):
        body = (text or "").strip()
        if not body:
            continue
        if is_statcard and n_table is not None and i >= n_table:
            continue    # печатная легенда бланка («…все пункты и части статьи УК…») — не наш текст
        for m in _NORMA_WORD.finditer(body):
            if m.start() == 0 and body[:1].isupper():
                continue        # дословный заголовок статьи — законная цитата
            findings.append((i + 1, "норма-словом",
                             "нормативная ссылка развёрнута словом — по §2.11 формата пишется "
                             "ТОЛЬКО сокращённо: ст., ч., п., пп., абз., и в описательной части "
                             "тоже. ⚠ В дословной цитате нормы разворот законен — проверить "
                             "контекст", m.group(0)))
            break               # одного флага на абзац достаточно

    # ⛔ Субъективная сторона висячим абзацем (правило 16): мотив и цель идут В ТКАНИ описания
    # деяния, а не отдельным блоком после него.
    _head_l = [x.strip() for x in paras if x and x.strip()][:_STATUS_HEAD_PARAS]
    if _MOTIV_DECISIVE.search("\n".join(_head_l)) or any(_MOTIV_OZ_TITLE.match(x) for x in _head_l):
        for i, text in enumerate(paras):
            body = (text or "").strip()
            if (body and len(body) <= _MOTIV_MAX_CHARS and _MOTIV_LEAD.match(body)
                    and _MOTIV_BODY.search(body) and not _MOTIV_FACTS.search(body)):
                findings.append((i + 1, "мотив-отдельным-абзацем",
                                 "субъективная сторона вынесена ОТДЕЛЬНЫМ абзацем и только отсылает к "
                                 "ранее описанному деянию. Мотив, цель и вид умысла излагаются в ткани "
                                 "описания деяния — обвинение должно читаться логично и последовательно "
                                 "(правило 16; замечание владельца, повторное). Внести содержание этого "
                                 "абзаца в описание соответствующего эпизода и удалить его",
                                 body[:110] + ("…" if len(body) > 110 else "")))

    # ⛔ Статус лица на ДАТУ документа (правило 41): утверждение о статусе есть, а первоисточник
    # не назван. Снимается ТОЛЬКО --status-verified — правкой текста этот флаг не закрыть, потому
    # что дефект не в тексте, а в том, откуда взято значение.
    if not status_verified:
        whole_doc = "\n".join(paras)
        _head_paras = [x.strip() for x in paras if x and x.strip()][:_STATUS_HEAD_PARAS]
        _head = "\n".join(_head_paras)
        decisive = (bool(_STATUS_DECISIVE.search(_head))
                    or any(_STATUS_OZ_TITLE.match(x) for x in _head_paras)
                    or (bool(_STATUS_VUD_TITLE.search(_head)) and bool(_STATUS_CH33.search(whole_doc))))
        if decisive:
            for i, text in enumerate(paras):
                if text and _STATUS_ASSERT.search(text):
                    body = text.strip()
                    findings.append((i + 1, "статус-без-подтверждения",
                                     "документ утверждает СТАТУС лица и при этом относится к жанру, где "
                                     "статус выбирает норму (мера пресечения, обвинение, ОЗ, "
                                     "подследственность). Статус, звание, должность и в/часть "
                                     "подтверждаются на ДАТУ документа первоисточником (выписка из "
                                     "приказа, справка части, послужной список), а не переносятся из "
                                     "ранее вынесенных документов. ⛔ Окончание военной службы — дата "
                                     "ИСКЛЮЧЕНИЯ ИЗ СПИСКОВ личного состава, а не приказа об увольнении "
                                     "(п. 11 ст. 38 ФЗ № 53-ФЗ). Подтвердил — перезапустить с "
                                     '--status-verified "<документ и его дата>" (правило 41, §16.34)',
                                     body[:110] + ("…" if len(body) > 110 else "")))
                    break

    # Локальный пример исключён из публичной поставки.
    # 25.08.2026). ч. 2 ст. 81 УПК его не требует — строка расползлась от доноров.
    if genre in _VESHCHDOK_GENRES or not genre:
        _head_v = "\n".join([x.strip() for x in paras if x and x.strip()][:_VESHCHDOK_HEAD_PARAS])
        _rx_v = _VESHCHDOK_TITLE if genre else _VESHCHDOK_TITLE_STRICT
        if _rx_v.search(_head_v):
            for i, text in enumerate(paras):
                if text and _VESHCHDOK_PROC.search(text):
                    body = text.strip()
                    findings.append((i + 1, "вещдок-копия-прокурору",
                                     "пункт о направлении копии постановления ПРОКУРОРУ — в "
                                     "постановлении о признании вещественным доказательством его "
                                     "быть не должно: ч. 2 ст. 81 УПК РФ (ред. 26.07.2026, сверено "
                                     "26.08.2026) требует только вынесения постановления и "
                                     "приобщения к делу. Копия прокурору обязательна для ВУД "
                                     "(ч. 4 ст. 146), ОВУД (ч. 4 ст. 148), приостановления и "
                                     "прекращения — но не для вещдока. Пункт удалить и "
                                     "перенумеровать резолютивку. ⚠ Это след ДОНОРА: в корпусе "
                                     "он в 11 постановлениях из 17 и во всех дословно один "
                                     "(указание владельца 25.08.2026)",
                                     body[:110] + ("…" if len(body) > 110 else "")))
                    break

    # ── Правило 33: одна фамилия с разными инициалами (текстовая проверка, работает всегда)
    findings += _check_initials(paras)

    # ── Зип-проверки: колонтитул-донор (правило 13) и нескреплённая подпись (§16.17).
    # ⛔ Читаем архив НАПРЯМУЮ zipfile — python-docx материализовал бы пустые колонтитулы.
    _raw = _docx_raw(path)
    if _raw is not None:
        findings += _check_header_donor(_raw, path)
        findings += _check_signature_break(_raw)

    # ⛔ РАЗМЕТКА ОЗ (§07.05.9): без пустых строк и полужирного заключение нечитаемо.
    # Жанр берём по --genre oz либо по заголовку в шапке — ОЗ ни с чем не спутать.
    _head_oz = [x.strip() for x in paras if x and x.strip()][:12]
    _is_oz = genre == "oz" or any(len(x) <= _OZ_TITLE_MAX and _OZ_TITLE_LINE.match(x)
                                  for x in _head_oz)
    if _is_oz:
        _st = _oz_markup_stats(path)
        if _st and _st[0] >= _OZ_MARKUP_MIN_PARAS:
            _tot, _empty, _bold = _st
            _share = _empty / _tot
            if _share < _OZ_EMPTY_MIN_SHARE or _bold < _OZ_BOLD_MIN:
                findings.append((0, "оз-без-разметки",
                                 "разметка ОЗ не сделана: абзацев {}, пустых {} ({:.0%}), "
                                 "полужирных {}. В корпусе владельца (15 ОЗ) пустых не меньше "
                                 "25 %, полужирных не меньше 3. Пустой строкой отбивается каждое "
                                 "доказательство и каждый смысловой блок; полужирным — заголовки "
                                 "разделов, зачин доказательства до первой запятой («Показания "
                                 'свидетеля Фамилия И.И.,») и формулы квалификации (§07.05.9). '
                                 "⛔ Не делать это правкой через первый run — см. флаг "
                                 "«абзац-целиком-жирный»; штатно docx_edit: bold_lead / "
                                 "bold_paragraph / insert_blank_after".format(
                                     _tot, _empty, _share, _bold), ""))

    # ⛔ РАБОЧИЙ МАРКЕР «[⇒» В ПОДПИСЫВАЕМОМ ДОКУМЕНТЕ (правило 38).
    # В файле с «(проект)» в имени маркеры законны и обязательны — там флага нет.
    if not _PROJECT_IN_NAME.search(os.path.basename(path)):
        _mk = [(i + 1, text.strip()) for i, text in enumerate(paras)
               if text and _WORK_MARKER in text]
        if _mk:
            _i, _b = _mk[0]
            _p = _b.find(_WORK_MARKER)
            findings.append((_i, "маркер-в-подписываемом",
                             "рабочий маркер «[⇒ …]» в документе, который печатают и подписывают "
                             "(всего таких абзацев: {}; первый — абзац {}). Маркеры предположений "
                             "живут ТОЛЬКО в проекте — файле с «(проект)» в имени (§06.01.13.10); "
                             "в протоколе для проведения их нет, перечень предположённого идёт "
                             "списком в ответе владельцу, а не в файле (правило 38). Либо снять "
                             "маркеры, либо переименовать файл в «… (проект).docx»".format(
                                 len(_mk), _i),
                             _b[max(0, _p - 20):_p + 90] + ("…" if len(_b) > _p + 90 else "")))

    # ⛔ ДАТА ДОКАЗАТЕЛЬСТВА ПОЗЖЕ ДАТЫ ДОКУМЕНТА (правило 54).
    _dd = _doc_date(paras)
    if _dd:
        _seen_later = {}
        for i, text in enumerate(paras):
            _b = (text or "").strip()
            if len(_b) < _DATE_MIN_PARA or _DATE_RULE_LINE.search(_b):
                continue          # линейка бланка, бирка, голая дата внутри комплекта
            if _DATE_FUTURE_CTX.search(_b) or _DATE_HANDOVER.search(_b):
                continue          # назначенное на будущее действие либо отметка о вручении
            if _place_date_line(text) or _blank_layout_line(text):
                continue
            _flat = re.sub(r"[\s\u00a0]+", " ", _b)
            for m in _DATE_NUM.finditer(_flat):
                _d = _mkdate(*m.groups())
                if not (_d and _d > _dd):
                    continue
                if _DATE_BEFORE_OK.search(_flat[max(0, m.start() - 30):m.start()]):
                    continue      # «срок … до 10.09.2026», «действительна до 31.07.2035»
                if _DATE_BIRTH.match(_flat[m.end():m.end() + 20]):
                    continue
                _seen_later.setdefault(m.group(0), (i + 1, _flat, m.start()))
        for _dt, (_i, _flat, _pos) in _seen_later.items():
            findings.append((_i, "доказательство-позже-документа",
                             "дата {} ПОЗЖЕ даты документа ({}). Документ не может стоять на "
                             "доказательстве, полученном после его даты (правило 54): либо убрать "
                             "это обстоятельство из фабулы, либо перенести дату документа — "
                             "спросив владельца, а не молча. ⚠ Дата в шапке бывает ДОНОРСКОЙ: "
                             "тогда чинить надо шапку. Законные будущие даты (срок «до …», явка, "
                             "отметка о вручении) отбиты автоматически".format(
                                 _dt, _dd.strftime("%d.%m.%Y")),
                             _flat[max(0, _pos - 60):_pos + 30].strip()))

    # ё вперемешку с е (файл целиком)
    whole = "\n".join(paras)
    n_yo = whole.count("ё") + whole.count("Ё")
    if 0 < n_yo:
        findings.append((0, "ё-в-тексте", f"буква «ё» встречается {n_yo} раз — финальная замена ё→е "
                                          "(или единообразно по всему документу)", ""))
    return findings


def main():
    _utf8_stdout()      # ⛔ иначе OSError [Errno 22] на первом же кириллическом сниппете
    args = [a for a in sys.argv[1:]]
    if args and args[0] in ("-h", "--help", "/?", "help"):
        print(__doc__)
        sys.exit(0)
    genre = None
    legal_style = "--legal-style" in args
    if legal_style:
        args.remove("--legal-style")
    if "--genre" in args:
        gi = args.index("--genre")
        genre = args[gi + 1] if gi + 1 < len(args) else None
        del args[gi:gi + 2]
    allow_foreign_reg = False
    if "--allow-foreign-reg" in args:
        allow_foreign_reg = True
        args.remove("--allow-foreign-reg")
    status_verified = None
    if "--status-verified" in args:
        si = args.index("--status-verified")
        status_verified = args[si + 1].strip() if si + 1 < len(args) else ""
        del args[si:si + 2]
        if not status_verified:
            print("--status-verified требует значения: чем именно подтверждён статус "
                  '(например: --status-verified "выписка из приказа № 118 от 04.08.2026"). '
                  "Пустое значение подтверждением не является (правило 41).")
            sys.exit(2)
    if not args:
        print(__doc__)
        sys.exit(2)
    path = args[0]

    findings = lint(path, genre, allow_foreign_reg, status_verified, legal_style=legal_style)
    if status_verified:
        print(f'статус лица подтверждён: {status_verified} — назвать это в ответе (правило 41).')
    if not findings:
        print("style_lint: чисто — механических огрехов не найдено.")
        if _LAST_AUTO_STATCARD:
            print("⚠ Файл опознан как БЛАНК СТАТКАРТЫ: проверены только ВПИСАННЫЕ значения, "
                  "печатные легенды формы не линтуются. «Чисто» здесь означает «во вписанном "
                  "огрехов нет», а не «карта заполнена верно»: состав и коды граф сверять по "
                  "`references/09-genres-stat-cards.md`, шрифт — `scripts/fix_statcard_font.py`.")
        print("(Смысл — нормы, ярлыки, права, уместность предупреждений — проверяет человек.)")
        sys.exit(0)

    print(f"style_lint: найдено {len(findings)} флаг(ов). Проверить перед выдачей:\n")
    for para_no, label, msg, snippet in findings:
        loc = f"абзац {para_no}" if para_no else "документ"
        print(f"  [{label}] {loc}: {msg}")
        if snippet:
            print(f"      → {snippet}")
    print("\nПримечание: «точка-с-запятой» и «прямые-кавычки» могут быть законны в дословной "
          "цитате нормы — проверить контекст, а не удалять слепо.")
    if any(f[1].startswith("стиль-проверить-") for f in findings):
        print("«стиль-проверить-*»: кандидаты на сверку, не доказанные дефекты. "
              "Смысл выбирается по источнику; при нескольких прочтениях показать их и вопрос "
              "для уточнения. Скрипт не проверяет право, не устанавливает факты и не меняет DOCX.")
    if any(f[1] == "чужая-регистрация" for f in findings):
        print("«чужая-регистрация»: если это документ-ВОЗВРАТ материала, который у нас не "
              "регистрировался, — флаг ложный, перезапустить с --genre vozvrat.")
    if any(f[1] == "подпись-разорвана" for f in findings):
        print("«подпись-разорвана»: флаг видит ОТСУТСТВИЕ `keep_with_next` у подписного блока и "
              "приблизительную позицию блока на листе. Сам разрыв страницы из .docx не виден — "
              "после правки прогнать рендер в PDF и посмотреть последнюю страницу (§16.17). "
              "⛔ Не ставить ручной разрыв страницы перед подписью.")
    if any(f[1] == "след-донора-колонтитул" for f in findings):
        print("«след-донора-колонтитул»: колонтитулы правятся отдельно от тела — открыть их в Word "
              "(Вставка → Колонтитулы, включая «Особый колонтитул для первой страницы») и сверить "
              "номер с делом. ⛔ Программно колонтитул создавать НЕ надо: обращение к нему в "
              "python-docx материализует пустую часть и ломает бланк (§8.2 п. 9).")
    if any(f[1] == "вещдок-копия-прокурору" for f in findings):
        print("«вещдок-копия-прокурору»: удалить пункт целиком и перенумеровать резолютивку "
              "(docx_edit: delete_paragraph + правка номеров). ⛔ После удаления абзаца ПОВТОРНО "
              "прогнать линт: сдвиг вёрстки поднимает флаг «подпись-разорвана» (§16.17), "
              "чинится {\"op\": \"glue_signature\"}.")
    if _LAST_AUTO_STATCARD:
        print("Файл опознан как БЛАНК СТАТКАРТЫ: линтуются только вписанные значения, печатные "
              "легенды формы не проверяются. Флаг на легенде неустраним и потому не выводится.")
    elif genre is None and any(f[1] in _TYPO_CHECKS for f in findings):
        print("Если типографский флаг сидит в подписном блоке постановления — перезапустить с "
              "--genre postanovlenie: тогда гасится и он (вёрстка «место — дата», печатные "
              "легенды и линейки гасятся всегда, без жанра).")
    if any(f[1] == "статус-без-подтверждения" for f in findings):
        print("«статус-без-подтверждения»: флаг снимается НЕ правкой текста, а первоисточником — "
              "открыть выписку из приказа либо справку части на дату документа и перезапустить с "
              '--status-verified "<документ и его дата>". Подтверждения нет — спросить владельца '
              "(правило 41), а не переносить статус из соседнего документа.")
    sys.exit(1)


if __name__ == "__main__":
    main()
