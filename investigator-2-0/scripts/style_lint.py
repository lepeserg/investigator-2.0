def _hf_paragraphs(doc):
    """Текст КОЛОНТИТУЛОВ (все секции, включая первую/чётную страницу).

    ⛔ КРИТИЧНО (инвариант §8.2 п. 9): обращение к `part.paragraphs` в python-docx вызывает
    `_get_or_add_definition()` и МАТЕРИАЛИЗУЕТ пустой колонтитул. Поэтому сначала читаем
    `is_linked_to_previous` — это свойство смотрит sectPr и НИЧЕГО не создаёт, — и в части
    без собственного определения не заходим вовсе.

    Зачем вообще: docx_edit с v17.4 ПИШЕТ в колонтитулы (№ дела, ФИО, исх.), а линтер их
    не читал — целая слепая зона. Замер на 300 реальных .docx: чтение колонтитулов добавляет
    флаги 1 файлу (0,3 %), и это ровно «остался-плейсхолдер» — реальный дефект боевого
    запроса ({ТЕЛ_ИСПОЛНИТЕЛЯ} в подвале). Постороннего шума не добавилось ни одного.
    """
    out = []
    for sec in doc.sections:
        parts = (sec.header, sec.footer,
                 getattr(sec, "first_page_header", None), getattr(sec, "first_page_footer", None),
                 getattr(sec, "even_page_header", None), getattr(sec, "even_page_footer", None))
        for part in parts:
            if part is None:
                continue
            try:
                if part.is_linked_to_previous:
                    continue            # своего определения нет — НЕ трогаем .paragraphs
            except Exception:
                continue
            out += [p.text for p in part.paragraphs]
            for tbl in part.tables:
                for row in tbl.rows:
                    for cell in row.cells:
                        out.append(cell.text)
    return out


def _extract_paragraphs(path):
    """Вернуть список строк текста (абзацы + ячейки таблиц + колонтитулы).
    Работает и без python-docx (тогда — только тело)."""
    try:
        import docx
        d = docx.Document(path)
        out = [p.text for p in d.paragraphs]
        for tbl in d.tables:
            for row in tbl.rows:
                for cell in row.cells:
                    out.append(cell.text)
        out += _hf_paragraphs(d)
        return out
    except Exception as docx_err:
        # Откат: тело из word/document.xml по общим правилам word_text.xml_text
        # (w:delText и коды полей w:instrText в текст не попадают)
        try:
            with zipfile.ZipFile(path) as z:
                xml = z.read("word/document.xml").decode("utf-8")
        except Exception as e:
            print(f"Не удалось открыть файл как .docx: {e}")
            sys.exit(2)
        print(f"⚠ python-docx не открыл файл ({docx_err}) — проверяется только тело "
              "document.xml, колонтитулы не прочитаны", file=sys.stderr)
        return xml_text(xml, paragraphs=True)


def _extract_statcard(path):
    """СТАТКАРТА: абзацы тела + ТОЛЬКО ВПИСАННЫЕ значения ячеек (последний непустой абзац ячейки).

    Возврат `(строки, сколько первых строк — тело)`; None — python-docx недоступен или файл не
    открылся (тогда вызывающий откатывается на обычное чтение и жанр вырождается в общий).

    Почему так, а не `cell.text`:
     · в бланке Ф-1/Ф-1.1/Ф-2 графа устроена «печатная легенда сверху → вписанное значение
       последним абзацем» («число    месяц       год   .» / «16.08.26»), поэтому именно последний
       абзац несёт то, за что отвечает следователь;
     · `cell.text` склеивает легенду со значением, и линтер ругался на текст ФОРМЫ;
     · обход идёт по элементам `w:tc` НАПРЯМУЮ, а не через `row.cells`: при вертикальном
       объединении одна и та же ячейка возвращается в КАЖДОЙ строке объединения, и легенды
       считались по 4 раза (это и раздувало счёт до 955 флагов на одной карте).
    """
    try:
        import docx
        from docx.oxml.ns import qn
        from docx.table import _Cell
        d = docx.Document(path)
    except Exception:
        return None
    try:
        body = [p.text for p in d.paragraphs]
        cells = []
        for tc in d.element.body.iter(qn("w:tc")):
            vals = [p.text for p in _Cell(tc, None).paragraphs if p.text and p.text.strip()]
            if vals:
                cells.append(vals[-1])
        return body + cells, len(body)
    except Exception:
        return None


