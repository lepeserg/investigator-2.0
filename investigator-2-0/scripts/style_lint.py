def _bold_share_paragraphs(path):
    """[(индекс, текст, доля жирных символов)] по абзацам ТЕЛА. Требует python-docx;
    без него проверка молча пропускается (текстовый фолбэк начертание не видит)."""
    try:
        import docx
        d = docx.Document(path)
    except Exception:
        return []
    out = []
    for i, p in enumerate(d.paragraphs):
        runs = [r for r in p.runs if r.text.strip()]
        if not runs:
            continue
        # ⚠ run.bold=None означает «наследовать» — жирность может быть задана СТИЛЕМ абзаца.
        # Прежняя версия считала только явный True и пропускала стилевой вариант той же граблиQ
        # (аудит 30.07.2026): в Word абзац полностью полужирный, а доля считалась нулевой.
        style_bold = False
        try:
            st = p.style
            while st is not None and style_bold is False:
                if st.font is not None and st.font.bold:
                    style_bold = True
                st = getattr(st, "base_style", None)
        except Exception:
            style_bold = False
        total = sum(len(r.text) for r in runs)
        bold = sum(len(r.text) for r in runs
                   if (r.bold is True) or (r.bold is None and style_bold))
        if total:
            out.append((i, p.text, bold / total))
    return out


