# ⛔ ВСЕ ЧЕТЫРЕ ШАБЛОНА ГАСЯТСЯ ВСЕГДА, без --genre. Причина — правило 40: линтер запускают без
#   жанра, и «вспомни флаг» механизмом не является. Каждый шаблон описывает строку, которая
#   ЦЕЛИКОМ является вёрсткой бланка и содержательного текста не несёт, поэтому настоящий огрех
#   в ней спрятаться не может.
#
# 1) Строка «МЕСТО — ДАТА» шапки постановления свёрстана табуляциями и пробелами
#    («г. Казань<TAB×9>            18.08.2026»). Замер на 50 постановлениях корпуса: она даёт
#    27 из 66 срабатываний `двойной-пробел`.
#    ⚠ День бывает НЕЗАПОЛНЕННЫМ («г. Казань      «   » марта 2026 г.») и подчёркиванием
#    («__.07.2026») — обе формы в шаблоне обязательны, иначе строка проскакивает мимо.
_PLACE_DATE_FULL = re.compile(
    r"^(?:г\.|гор\.|с\.|пос\.|пгт\.?|д\.|аг\.|ст-ца)\s?[А-ЯЁ][А-Яа-яЁё\- ]{1,30}?\s+"
    r"(?:«[^»]{0,4}»|«?\d{1,2}»?|_{2,})\s*[. ]\s*(?:\d{1,2}|_{2,}|[а-яё]{3,9})"
    r"\s*[. ]?\s*(?:\d{2,4}|_{2,})\s*(?:г\.?(?:ода)?)?$")
# 2) ПЕЧАТНАЯ ЛЕГЕНДА графы бланка: «(подпись)», «(место составления)», «классный чин или
#    звание, фамилия, инициалы)», «(должность руководителя следственного органа,». Признак —
#    круглая скобка на границе строки и отсутствие своего предложения.
#    Частый случай — ДВЕ легенды в одной строке: «(подпись)<TAB×4>(инициалы, фамилия)». Это
#    подвал каждого блока подписи в бланке протокола, на замере он даёт больше половины остатка
#    `двойной-пробел`, поэтому строка «только легенды и разделители» описана отдельно.
_BLANK_LEGEND = re.compile(r"^\([^)]{0,140}\)?$|^[а-яё][^()]{0,140}\)$")
_LEGEND_ONLY = re.compile(r"^(?:\([^()]{0,140}\)|[\s \t_.,;:–-])+$")
# Локальный пример исключён из публичной поставки.
#    пробелы вокруг подчёркиваний это вёрстка поля для заполнения.
_BLANK_RULE = re.compile(r"_{3,}")
# 4) ШАПКА формы, набранная ВРАЗРЯДКУ: «П р и л о ж е н и е  2» — так свёрстаны бланки ГВП
#    Ф-1/Ф-1.1/Ф-1.2/Ф-2. Пять и более односимвольных «слов» подряд обычным текстом не бывают.
_SPACED_OUT = re.compile(r"^(?:\S ){4,}\S")


def _place_date_line(text):
    """Строка ЦЕЛИКОМ «населённый пункт — дата» (шапка постановления). Пробелы и табы в ней —
    вёрстка бланка. Сравнение идёт по СХЛОПНУТЫМ пробелам, иначе табуляции ломают шаблон."""
    return bool(_PLACE_DATE_FULL.match(re.sub(r"[\s ]+", " ", text or "").strip()))


def _blank_layout_line(text):
    """Печатная легенда графы, линейка бланка либо шапка вразрядку — типографике не подлежит."""
    t = (text or "").strip()
    return bool(t) and (bool(_BLANK_LEGEND.match(t)) or bool(_LEGEND_ONLY.match(t))
                        or bool(_BLANK_RULE.search(t)) or bool(_SPACED_OUT.match(t)))


def _first_inner(rx, text):
    """Первое совпадение, перед которым есть НЕПРОБЕЛЬНЫЙ текст.

    ⛔ Отступ абзаца — не «двойной пробел». В бланках корпуса абзац часто начинается с несколь-
    ких пробелов вместо отступа стиля, и проверка ловила ровно этот отступ: настоящая сдвоенность
    внутри строки при этом никуда не девается — `finditer` доходит до неё следующим шагом."""
    for m in rx.finditer(text):
        if text[:m.start()].strip():
            return m
    return None


