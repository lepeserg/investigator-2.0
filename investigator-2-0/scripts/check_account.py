# -*- coding: utf-8 -*-
"""check_account.py — КОНТРОЛЬНЫЙ КЛЮЧ номера счёта по БИК (арифметическая проверка).

⛔ Не путать со счётом карты (16-19 цифр, алгоритм Луна) — здесь ЛИЦЕВОЙ счёт, 20 цифр.

АЛГОРИТМ (Положение Банка России о плане счетов, порядок расчёта контрольного ключа).
  Перед 20-значным номером счёта ставится трёхзначный УСЛОВНЫЙ НОМЕР участника расчётов,
  получается строка в 23 знака. Каждый знак умножается на весовой коэффициент из цикла
  7-1-3 (7,1,3,7,1,3,…), от каждого произведения берётся МЛАДШИЙ разряд, младшие разряды
  складываются. Номер верен, если сумма кратна 10.
  Условный номер участника расчётов:
    · счёт открыт В ПОДРАЗДЕЛЕНИИ БАНКА РОССИИ (корсчёт/субсчёт 301хх, казначейские 03ххх,
      счета ФК 40101/40102/40105/40116) — «0» и 5-й, 6-й разряды БИК;
    · счёт открыт В КРЕДИТНОЙ ОРГАНИЗАЦИИ (обычный клиентский 40817, 40802, 42301 и т.п.) —
      три последних разряда БИК.

Порядок аргументов ЛЮБОЙ: 9 цифр — это БИК, 20 цифр — счёт; счетов можно передать
несколько (сравнить варианты прочтения одного номера за один запуск). Пробелы, точки
и дефисы внутри номеров игнорируются.

Флаги:
    --key       показать, каким ДОЛЖЕН быть 9-й знак (контрольный ключ) при этом БИК
    --quiet     только код возврата, без вывода
    --strict    считать сошедшимся только совпадение по ветке, выбранной по типу счёта

Код возврата: 0 — сходится; 1 — не сходится ни по одной ветке; 2 — сошлось только по
альтернативной ветке (проверить, тот ли БИК); 3 — ошибка во входных данных.
При нескольких счетах возвращается ХУДШИЙ код."""
import argparse
import re
import sys

try:  # иначе кириллица в выводе ломается на Windows-консоли (cp866/cp1251)
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:
    pass

WEIGHTS = (7, 1, 3) * 8          # 24 коэффициента, используются первые 23
KEY_POS = 8                      # индекс контрольного ключа внутри номера счёта

# Балансовые счета, которые открываются В ПОДРАЗДЕЛЕНИИ БАНКА РОССИИ: корсчета и субсчета
# кредитных организаций (301хх), казначейские счета (03ххх) и счета Федерального
# казначейства (40101/40102/40105/40116). Для них условный номер участника расчётов
# берётся иначе — см. докстринг. Список короткий намеренно: каждая позиция подтверждена
# парой счёт+БИК из корпуса, догадки сюда не добавлять — ложная ветка даёт ложное
# «не сходится» на верном номере.
CBR_PREFIXES = ("301", "03", "40101", "40102", "40105", "40116")

# Насколько плох результат: 0 — чисто, 2 — сошлось не по той ветке, 1 — не сошлось вовсе.
SEVERITY = {0: 0, 2: 1, 1: 2, 3: 3}

CURRENCY = {
    "810": "рубли", "643": "рубли", "840": "доллары США", "978": "евро",
    "156": "юани", "398": "тенге", "933": "белорусские рубли", "784": "дирхамы ОАЭ",
}


def normalize(num):
    """Убирает пробелы, точки, дефисы и неразрывные пробелы из номера."""
    return re.sub(r"[\s.\-–— ]", "", str(num or ""))


def uslovny_nomer(account, bik):
    """Возвращает (условный_номер_основной, условный_номер_альтернативный, ветка).

    Ветка выбирается по балансовому счёту (первые 5 знаков номера): счета
    подразделений Банка России считаются по «0»+5-6 разрядам БИК, остальные —
    по трём последним разрядам БИК. Альтернативная ветка возвращается затем,
    чтобы при несовпадении сказать, не подставлен ли БИК другой организации.
    """
    v_cb = "0" + bik[4:6]        # счёт открыт в подразделении Банка России
    v_ko = bik[6:9]              # счёт открыт в кредитной организации
    if account.startswith(CBR_PREFIXES):
        return v_cb, v_ko, "счёт в подразделении Банка России"
    return v_ko, v_cb, "счёт в кредитной организации"


def _summa(prefix, account):
    """Сумма младших разрядов произведений на весовые коэффициенты 7-1-3."""
    line = prefix + account
    return sum((int(ch) * WEIGHTS[i]) % 10 for i, ch in enumerate(line))


def matches(account, prefix):
    """Сходится ли контрольный ключ при данном условном номере участника расчётов."""
    return _summa(prefix, account) % 10 == 0


def control_key(account, prefix):
    """Каким ДОЛЖЕН быть 9-й знак счёта при данном условном номере.

    Ключ стоит на позиции с весом 3, поэтому подбирается перебором десяти цифр —
    это надёжнее формулы и не зависит от того, на какой разряд попал цикл 7-1-3.
    """
    for d in "0123456789":
        cand = account[:KEY_POS] + d + account[KEY_POS + 1:]
        if matches(cand, prefix):
            return d
    return None


def check(account, bik):
    """Проверяет пару счёт+БИК. Возвращает словарь с разбором и кодом возврата.

    Ключи: ok, code, ветка, условный, условный_альт, по_основной, по_альтернативной,
    ключ_есть, ключ_нужен, валюта.
    """
    main, alt, branch = uslovny_nomer(account, bik)
    by_main = matches(account, main)
    by_alt = matches(account, alt)
    if by_main:
        code = 0
    elif by_alt:
        code = 2
    else:
        code = 1
    return {
        "счёт": account,
        "бик": bik,
        "ветка": branch,
        "условный": main,
        "условный_альт": alt,
        "по_основной": by_main,
        "по_альтернативной": by_alt,
        "ok": by_main or by_alt,
        "code": code,
        "ключ_есть": account[KEY_POS],
        "ключ_нужен": control_key(account, main),
        "валюта": CURRENCY.get(account[5:8], "код " + account[5:8]),
    }


def report(res, show_key=False):
    """Печатает разбор одной пары счёт+БИК."""
    verdict = {0: "СХОДИТСЯ", 1: "НЕ СХОДИТСЯ", 2: "СХОДИТСЯ, НО НЕ ПО ТОЙ ВЕТКЕ"}[res["code"]]
    print("%s + БИК %s — %s" % (res["счёт"], res["бик"], verdict))
    print("   балансовый счёт %s · валюта %s (%s) · ключ %s · %s"
          % (res["счёт"][:5], res["счёт"][5:8], res["валюта"], res["ключ_есть"], res["ветка"]))
    print("   условный номер участника расчётов: %s" % res["условный"])
    if res["code"] == 1:
        need = res["ключ_нужен"]
        print("   ⛔ номер неверен: при этом БИК 9-м знаком должен стоять «%s», а стоит «%s»."
              % (need, res["ключ_есть"]))
        print("      Причина — ошибка в номере счёта ЛИБО не тот БИК. Сверить с ответом банка.")
    elif res["code"] == 2:
        print("   ⚠ по ветке «%s» не сходится, но сходится по другой (условный номер %s)."
              % (res["ветка"], res["условный_альт"]))
        print("      Так бывает, когда рядом стоит БИК другой организации (например, БИК")
        print("      казначейства при едином казначейском счёте). Проверить пару счёт/БИК.")
    if show_key:
        print("   контрольный ключ при этом БИК должен быть: %s" % res["ключ_нужен"])


def main():
    ap = argparse.ArgumentParser(
        description="Проверка контрольного ключа номера счёта по БИК",
        epilog="Порядок аргументов любой: 9 цифр — БИК, 20 цифр — счёт (можно несколько).")
    ap.add_argument("числа", nargs="*", help="номер(а) счёта (20 цифр) и БИК (9 цифр)")
    ap.add_argument("--key", action="store_true", help="показать, каким должен быть 9-й знак")
    ap.add_argument("--quiet", action="store_true", help="без вывода, только код возврата")
    ap.add_argument("--strict", action="store_true",
                    help="сошедшимся считать только совпадение по ветке типа счёта")
    args = ap.parse_args()

    accounts, biks, bad = [], [], []
    for raw in args.числа:
        num = normalize(raw)
        if not num.isdigit():
            bad.append(raw)
        elif len(num) == 20:
            accounts.append(num)
        elif len(num) == 9:
            biks.append(num)
        else:
            bad.append(raw)

    if bad or not accounts or len(biks) != 1:
        if not args.quiet:
            for b in bad:
                print("Не номер счёта и не БИК: «%s» (нужно 20 или 9 цифр)" % b)
            if not accounts:
                print("Не передан номер счёта (20 цифр).")
            if len(biks) > 1:
                print("Передано несколько БИК (%s) — оставить один." % ", ".join(biks))
            elif not biks:
                print("Не передан БИК (9 цифр).")
            print('Вспомогательная функция. Частный пример исключён из публичной версии.')
        return 3

    bik = biks[0]
    worst = 0
    for acc in accounts:
        res = check(acc, bik)
        if args.strict and res["code"] == 2:
            res["code"] = 1
        if not args.quiet:
            report(res, show_key=args.key)
            if acc != accounts[-1]:
                print()
        if SEVERITY[res["code"]] > SEVERITY[worst]:
            worst = res["code"]
    return worst


if __name__ == "__main__":
    sys.exit(main())
